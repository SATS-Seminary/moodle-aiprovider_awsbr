namespace aiprovider_awsbr\privacy;

use core_privacy\local\metadata\collection;
use core_privacy\local\request\approved_contextlist;
use core_privacy\local\request\approved_userlist;
use core_privacy\local\request\contextlist;
use core_privacy\local\request\userlist;

/**
 * Privacy Subsystem for aiprovider_awsbr.
 *
 * This plugin sends data to AWS Bedrock for AI inference. It does not store any
 * additional user data beyond what is already recorded by core_ai's standard
 * audit tables (ai_action_register + ai_action_generate_text, etc.).
 *
 * The external_location metadata entry discloses that prompts, images, and
 * responses cross the AWS API boundary. Cross-Region inference may route
 * computation to AWS commercial regions outside South Africa (relevant for POPIA
 * compliance — ensure a current Data Processing Agreement covers this pathway).
 *
 * Stream A5 — fully implements \core_privacy\local\request\plugin\provider and
 * \core_privacy\local\request\core_userlist_provider, matching aiprovider_azureai.
 *
 * @package    aiprovider_awsbr
 * @copyright  2026 South African Theological Seminary (ict@sats.ac.za)
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 * @codeCoverageIgnore
 */
class provider implements
    \core_privacy\local\metadata\provider,
    \core_privacy\local\request\core_userlist_provider,
    \core_privacy\local\request\plugin\provider {
    #[\Override]
    public static function get_metadata(collection $collection): collection {
        $collection->add_external_location_link('aws_bedrock', [
            'prompt'   => 'privacy:metadata:aws_bedrock:prompt',
            'image'    => 'privacy:metadata:aws_bedrock:image',
            'response' => 'privacy:metadata:aws_bedrock:response',
        ], 'privacy:metadata:aws_bedrock');

        return $collection;
    }

    /**
     * Get the list of contexts that contain user information for the specified user.
     *
     * This plugin delegates its storage to core_ai, which handles the actual
     * ai_action_register entries. No additional context data is stored here.
     *
     * @param int $userid The user to search.
     * @return contextlist
     */
    #[\Override]
    public static function get_contexts_for_userid(int $userid): contextlist {
        return new contextlist();
    }

    /**
     * Get the list of users who have data within a context.
     *
     * This plugin stores no user data beyond what core_ai tracks centrally.
     *
     * @param userlist $userlist The userlist to add users to.
     */
    #[\Override]
    public static function get_users_in_context(userlist $userlist): void {
        // No plugin-local user data stored; nothing to add.
    }

    /**
     * Export all user data for the specified user, in the specified contexts.
     *
     * All data generated by this provider (prompts, responses, token counts) is
     * stored by core_ai in its standard tables and exported by core_ai's own
     * privacy provider. This plugin does not duplicate that export.
     *
     * @param approved_contextlist $contextlist The approved contexts to export.
     */
    #[\Override]
    public static function export_user_data(approved_contextlist $contextlist): void {
        // Handled by core_ai\privacy\provider.
    }

    /**
     * Delete all data for all users in the specified context.
     *
     * No plugin-local tables store user data; deletion is handled by core_ai.
     *
     * @param \context $context The specific context to delete data for.
     */
    #[\Override]
    public static function delete_data_for_all_users_in_context(\context $context): void {
        // Handled by core_ai\privacy\provider.
    }

    /**
     * Delete all user data for the specified user, in the specified contexts.
     *
     * @param approved_contextlist $contextlist The approved contexts and user information.
     */
    #[\Override]
    public static function delete_data_for_user(approved_contextlist $contextlist): void {
        // Handled by core_ai\privacy\provider.
    }

    /**
     * Delete multiple users within a single context.
     *
     * @param approved_userlist $userlist The approved context and user information to delete.
     */
    #[\Override]
    public static function delete_data_for_users(approved_userlist $userlist): void {
        // Handled by core_ai\privacy\provider.
    }
}
